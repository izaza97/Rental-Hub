-- ============================================================================
-- PS RENTAL HUB - SUPABASE POSTGRESQL MIGRATION (INIT)
-- Sistem Informasi Pengelolaan Rental PlayStation — Kelompok 12 UNINDRA
-- Skema ini menggantikan database/ps_rental_hub.sql (MySQL lokal) dan
-- skema auto-create di SQLite (better-sqlite3) yang lama.
--
-- Cara pakai (Supabase SQL Editor):
--   1. Buka Supabase Dashboard → SQL Editor → New query
--   2. Paste seluruh file ini → klik Run
--   (atau via CLI: supabase db push)
--
-- Catatan kompatibilitas dari MySQL/SQLite:
--   - ENUM MySQL        -> TEXT + CHECK CONSTRAINT
--   - DATETIME          -> TIMESTAMP (without time zone) — format "YYYY-MM-DD HH:MM:SS"
--   - AUTO_INCREMENT    -> INTEGER GENERATED BY DEFAULT AS IDENTITY
--   - TINYINT(1)        -> BOOLEAN
--   - LIKE case-insens. -> gunakan ILIKE di query aplikasi (sudah diterapkan)
--   - Seed data + sequence reset disertakan di bagian bawah
-- ============================================================================

-- 1. Tabel Users (SRS 4.1, NFR-06 Bcrypt, NFR-07 RBAC)
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  name          VARCHAR(100) NOT NULL,
  role          VARCHAR(20)  NOT NULL DEFAULT 'Operator'
                CHECK (role IN ('Super Admin','Manajer','Operator','Pemilik')),
  status        VARCHAR(10)  NOT NULL DEFAULT 'Aktif'
                CHECK (status IN ('Aktif','Nonaktif')),
  last_active   TIMESTAMP NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_username UNIQUE (username)
);

-- 2. Tabel Units PlayStation (SRS 4.3, FR-7 s/d FR-10)
CREATE TABLE IF NOT EXISTS units (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           VARCHAR(20) NOT NULL,
  name           VARCHAR(50) NOT NULL,
  ps_type        VARCHAR(10) NOT NULL DEFAULT 'PS5'
                 CHECK (ps_type IN ('PS4','PS5')),
  room_type      VARCHAR(20) NOT NULL DEFAULT 'Reguler'
                 CHECK (room_type IN ('VIP Room','Reguler','VR Corner','Home Rental')),
  price_per_hour NUMERIC(12,2) NOT NULL DEFAULT 0,
  status         VARCHAR(20) NOT NULL DEFAULT 'Tersedia'
                 CHECK (status IN ('Tersedia','Disewa','Maintenance')),
  features       VARCHAR(255) NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_units_code UNIQUE (code)
);
CREATE INDEX IF NOT EXISTS idx_units_status ON units (status);
CREATE INDEX IF NOT EXISTS idx_units_ps_type ON units (ps_type);

-- 3. Tabel Customers / Pelanggan (SRS 4.4, FR-11 s/d FR-13)
CREATE TABLE IF NOT EXISTS customers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  nik        VARCHAR(30)  NULL,
  phone      VARCHAR(20)  NULL,
  address    VARCHAR(255) NULL,
  points     INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_customers_name ON customers (name);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers (phone);

-- 4. Tabel Transactions / Transaksi Rental (SRS 4.5, FR-14 s/d FR-20)
CREATE TABLE IF NOT EXISTS transactions (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_code   VARCHAR(25) NOT NULL,
  customer_id    INTEGER NULL,
  customer_name  VARCHAR(100) NOT NULL,
  customer_phone VARCHAR(20) NULL,
  unit_id        INTEGER NULL,
  unit_name      VARCHAR(50) NOT NULL,
  booking_source VARCHAR(20) NOT NULL DEFAULT 'Admin POS'
                 CHECK (booking_source IN ('Admin POS','Client Online','Home Rental')),
  start_time     TIMESTAMP NOT NULL,
  end_time       TIMESTAMP NOT NULL,
  return_time    TIMESTAMP NULL,
  duration_hours NUMERIC(6,2) NOT NULL DEFAULT 1,
  price_per_hour NUMERIC(12,2) NOT NULL DEFAULT 0,
  addons_total   NUMERIC(14,2) NOT NULL DEFAULT 0,
  subtotal       NUMERIC(14,2) NOT NULL DEFAULT 0,
  discount       NUMERIC(14,2) NOT NULL DEFAULT 0,
  penalty        NUMERIC(14,2) NOT NULL DEFAULT 0,
  total          NUMERIC(14,2) NOT NULL DEFAULT 0,
  payment_status VARCHAR(15) NOT NULL DEFAULT 'Lunas'
                 CHECK (payment_status IN ('Lunas','Belum Lunas')),
  payment_method VARCHAR(30) NOT NULL DEFAULT 'cash',
  created_by     VARCHAR(50) NOT NULL DEFAULT 'system',
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_transactions_invoice UNIQUE (invoice_code),
  CONSTRAINT fk_trx_customer FOREIGN KEY (customer_id)
    REFERENCES customers (id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_trx_unit FOREIGN KEY (unit_id)
    REFERENCES units (id) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_transactions_customer ON transactions (customer_id);
CREATE INDEX IF NOT EXISTS idx_transactions_unit ON transactions (unit_id);
CREATE INDEX IF NOT EXISTS idx_transactions_created ON transactions (created_at);

-- 5. Tabel Stock Aksesori & Snack Bar
CREATE TABLE IF NOT EXISTS stock (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  price      NUMERIC(12,2) NOT NULL DEFAULT 0,
  qty        INTEGER NOT NULL DEFAULT 0,
  category   VARCHAR(20) NOT NULL DEFAULT 'Aksesori'
             CHECK (category IN ('Aksesori','Makanan','Minuman')),
  sold       INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Tabel Detail Add-ons Transaksi
CREATE TABLE IF NOT EXISTS transaction_addons (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id INTEGER NOT NULL,
  stock_id       INTEGER NULL,
  item_name      VARCHAR(100) NOT NULL,
  price          NUMERIC(12,2) NOT NULL DEFAULT 0,
  qty            INTEGER NOT NULL DEFAULT 1,
  subtotal       NUMERIC(14,2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_addon_trx FOREIGN KEY (transaction_id)
    REFERENCES transactions (id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_addon_stock FOREIGN KEY (stock_id)
    REFERENCES stock (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- 7. Tabel Promo / Kupon Diskon
CREATE TABLE IF NOT EXISTS promos (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(30) NOT NULL,
  discount_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
  description      VARCHAR(255) NULL,
  expired_at       DATE NULL,
  used_count       INTEGER NOT NULL DEFAULT 0,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_promos_code UNIQUE (code)
);

-- 8. Tabel Activity Logs / Audit Trail (NFR-08)
CREATE TABLE IF NOT EXISTS activity_logs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username   VARCHAR(50) NOT NULL,
  action     VARCHAR(100) NOT NULL,
  detail     VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_logs_created ON activity_logs (created_at);

-- 9. Tabel Deposits (Jaminan Sewa Bawa Pulang)
CREATE TABLE IF NOT EXISTS deposits (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_code   VARCHAR(25) NULL,
  unit_name      VARCHAR(50) NOT NULL,
  customer_name  VARCHAR(100) NOT NULL,
  customer_nik   VARCHAR(30) NULL,
  deposit_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
  status         VARCHAR(20) NOT NULL DEFAULT 'Ditahan'
                 CHECK (status IN ('Ditahan','Dikembalikan')),
  return_date    DATE NULL,
  notes          VARCHAR(255) NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 10. Tabel Games (Katalog Game Portal Client)
CREATE TABLE IF NOT EXISTS games (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      VARCHAR(100) NOT NULL,
  platform   VARCHAR(15) NOT NULL DEFAULT 'PS5'
             CHECK (platform IN ('PS4','PS5','PS4 & PS5')),
  genre      VARCHAR(60) NOT NULL,
  rating     NUMERIC(3,1) NOT NULL DEFAULT 4.8,
  players    VARCHAR(30) NOT NULL DEFAULT '1-2 Pemain',
  is_popular BOOLEAN NOT NULL DEFAULT TRUE
);

-- 11. Tabel Game Requests (Request Instalasi Game dari Client ke Admin)
CREATE TABLE IF NOT EXISTS game_requests (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name    VARCHAR(100) NOT NULL,
  game_title       VARCHAR(120) NOT NULL,
  platform         VARCHAR(10) NOT NULL DEFAULT 'PS5'
                   CHECK (platform IN ('PS4','PS5')),
  unit_preference VARCHAR(50) NULL,
  status           VARCHAR(15) NOT NULL DEFAULT 'Menunggu'
                   CHECK (status IN ('Menunggu','Disetujui','Selesai')),
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- VIEWS DASHBOARD (FR-4 s/d FR-6)
-- ============================================================================
CREATE OR REPLACE VIEW v_unit_status AS
SELECT status, COUNT(*) AS jumlah_unit FROM units GROUP BY status;

CREATE OR REPLACE VIEW v_dashboard_harian AS
SELECT COUNT(*) AS transaksi_hari_ini, COALESCE(SUM(total),0) AS pendapatan_hari_ini
FROM transactions WHERE created_at::date = CURRENT_DATE;

CREATE OR REPLACE VIEW v_dashboard_bulanan AS
SELECT COUNT(*) AS transaksi_bulan_ini, COALESCE(SUM(total),0) AS pendapatan_bulan_ini
FROM transactions
WHERE date_trunc('month', created_at) = date_trunc('month', CURRENT_DATE);

